"""Interactive forecasting section for the Streamlit dashboard."""
import numpy as np
import plotly.graph_objects as go
import streamlit as st

from forecast import ALL_CAMPAIGNS, growth_percent, scenario_forecast, train_forecast
from theme import earth_section, style_chart

DEFAULTS = dict(forecast_months=12, forecast_adjustment=0,
                forecast_campaign=ALL_CAMPAIGNS, forecast_view="Compare Both",
                forecast_range=True, forecast_table=True)


@st.cache_data(show_spinner=False)
def cached_forecast(donations, campaign):
    return train_forecast(donations, campaign)


def reset_forecast_controls():
    for key, value in DEFAULTS.items():
        st.session_state[key] = value


def forecast_chart(history, table, view, show_range):
    fig = go.Figure()
    style_chart(fig)
    fig.add_trace(go.Scatter(
        x=history.index, y=history.values, name="Historical actual", mode="lines+markers",
        line=dict(color="#183d66", width=3),
        hovertemplate="Month: %{x|%b %Y}<br>Actual: $%{y:,.2f}<extra></extra>",
    ))
    custom = np.column_stack([table.baseline, table.adjusted, table.upper])
    hover = ("Month: %{x|%b %Y}<br>Baseline forecast: $%{customdata[0]:,.2f}"
             "<br>Adjusted scenario: $%{customdata[1]:,.2f}"
             "<br>Upper bound: $%{customdata[2]:,.2f}<extra></extra>")
    if show_range:
        fig.add_trace(go.Scatter(
            x=table.month, y=table.upper, name="Upper forecast bound", mode="lines",
            line=dict(color="#88794c", width=2),
            customdata=custom, hovertemplate=hover,
        ))
    for visible, field, name, color in [
        (view != "What-If Scenario", "baseline", "Baseline forecast", "#cf731d"),
        (view != "Baseline Forecast", "adjusted", "What-if scenario", "#397742"),
    ]:
        if visible:
            fig.add_trace(go.Scatter(
                x=table.month, y=table[field], name=name, mode="lines+markers",
                line=dict(color=color, width=3, dash="dash"), customdata=custom, hovertemplate=hover,
            ))
    fig.update_layout(title=dict(text=""), height=450, hovermode="x unified",
                      xaxis_title="Year-Month", yaxis_title="Donations ($)",
                      xaxis_title_font=dict(family="Georgia, serif", size=16, color="#173d29"),
                      yaxis_title_font=dict(family="Georgia, serif", size=16, color="#173d29"),
                      legend=dict(orientation="h", y=1.18, font=dict(color="#173d29", size=13)),
                      margin=dict(t=90, b=50, l=50, r=20))
    start = table.month.iloc[0].to_pydatetime()
    fig.add_shape(type="line", x0=start, x1=start, y0=0, y1=1, yref="paper",
                  line=dict(color="#294d3b", dash="dot", width=2))
    fig.add_annotation(x=start, y=1, yref="paper", text="Forecast begins", showarrow=False,
                       xanchor="left", yanchor="bottom", font=dict(color="#173d29"))
    return fig


def render_forecast(donations):
    with earth_section("forecast"):
        st.subheader("Interactive Forecast Controls")
        for key, value in DEFAULTS.items():
            if key not in st.session_state:
                st.session_state[key] = value
        left, right = st.columns(2)
        months = left.slider("Number of Months to Forecast", 3, 12, step=1,
                            key="forecast_months", help="Choose how many future months you want to display.")
        adjustment = right.slider(
            "What-If Donation Adjustment", -20, 20, step=1, format="%d%%",
            key="forecast_adjustment",
            help="Explore how the forecast could change under a lower or higher donation scenario.",
        )
        campaign = left.selectbox("Campaign", [ALL_CAMPAIGNS] + sorted(donations.campaign.dropna().unique()),
                                  key="forecast_campaign")
        view = right.radio("Chart View", ["Baseline Forecast", "What-If Scenario", "Compare Both"],
                           key="forecast_view")
        show_range = left.checkbox("Show Upper Forecast Bound", key="forecast_range")
        show_table = right.checkbox("Show Forecast Table", key="forecast_table")
        st.button("Reset Forecast Controls", on_click=reset_forecast_controls)
        st.write(
            "The baseline forecast is generated by the trained forecasting model. The what-if adjustment "
            "allows users to explore possible higher or lower donation scenarios. Changing the adjustment "
            "does not change or retrain the model."
        )
        st.info("This forecast is an academic prototype based on synthetic data and is not a guaranteed financial projection.")
        bundle = cached_forecast(donations, campaign)
        if bundle["warning"]:
            st.warning(bundle["warning"])
            return
        history = bundle["history"]
        table = scenario_forecast(bundle["forecast"], months, adjustment)
        previous = float(history.iloc[-months:].sum())
        baseline = float(table.baseline.sum())
        adjusted = float(table.adjusted.sum())
        st.markdown(f"#### Forecast: {table.month.iloc[0]:%B %Y} – {table.month.iloc[-1]:%B %Y}")
        st.caption(f"Campaign: {campaign} · {months} months · Previous period: "
                   f"{history.index[-months]:%B %Y} – {history.index[-1]:%B %Y}")
        c1, c2, c3 = st.columns(3)
        c1.metric("Previous-period actual donations", f"${previous:,.2f}")
        c2.metric("Baseline predicted donations", f"${baseline:,.2f}")
        c3.metric("Adjusted scenario donations", f"${adjusted:,.2f}")
        c1, c2 = st.columns(2)
        for column, label, total in [(c1, "Baseline predicted growth", baseline),
                                      (c2, "Adjusted scenario growth", adjusted)]:
            growth = growth_percent(total, previous)
            column.metric(label, f"{growth:+.1f}%" if growth is not None else "N/A")
        if previous == 0:
            st.caption("Growth is unavailable because previous-period donations are zero.")
        st.plotly_chart(forecast_chart(history, table, view, show_range), theme=None, width="stretch")
        st.caption("Ridge regression uses a monthly trend and annual seasonality. The latest recorded month "
                   "is included as recorded and may be incomplete. Missing months within the history are treated as zero. "
                   "The upper forecast bound describes the baseline only: an approximate upper limit based on held-out errors, "
                   "not a guaranteed limit or an adjusted scenario bound.")
        metrics = bundle["metrics"]
        st.markdown("##### Forecast Evaluation")
        c1, c2 = st.columns(2)
        c1.metric("Holdout MAE", f"${metrics['mae']:,.2f}")
        c2.metric("Holdout RMSE", f"${metrics['rmse']:,.2f}")
        st.caption(f"Chronological backtest: trained on earlier months and evaluated on the last {metrics['months']} "
                   "historical months for the selected campaign. Final baseline is then fitted on all available months.")
        if show_table:
            display = table.rename(columns={"month": "Forecast month", "baseline": "Baseline forecast",
                                           "adjustment": "Adjustment percentage", "adjusted": "Adjusted forecast",
                                           "upper": "Upper bound"}).copy()
            display["Forecast month"] = display["Forecast month"].dt.strftime("%B %Y")
            table_columns = ["Forecast month", "Baseline forecast", "Adjustment percentage", "Adjusted forecast",
                             "Upper bound"]
            styled_display = display[table_columns].style.set_properties(**{
                "color": "#173d29", "background-color": "#f0f5e9",
            })
            st.dataframe(styled_display, hide_index=True, width="stretch",
                         column_config={name: st.column_config.NumberColumn(format="$%.2f") for name in
                                        ["Baseline forecast", "Adjusted forecast", "Upper bound"]})
